@pytest.mark.slow
def test_perf_smoke_plan(tmp_path: Path) -> None:
    """A large index is planned in bounded time and memory; prints the rate."""
    import time as time_module

    generated = gen.generate(
        tmp_path / "perf.csv",
        gen.GenOptions(
            seed=77,
            min_files=120_000,
            files_per_dir=12,
            dirs_per_dir=4,
            min_depth=6,
            collect_entries=False,
        ),
    )
    db_path = tmp_path / "perf.db"
    ingest_csv(generated.path, db_path)
    conn = db.open_db(db_path)
    started = time_module.perf_counter()
    try:
        plan = planner.build_plan(
            conn,
            rules.load_rules(),
            targets=(D_TARGET,),
            min_size=1 * MIB,
            top=20,
            now=NOW,
            db_path=str(db_path),
        )
    finally:
        entries = db.entry_count(conn)
        conn.close()
    elapsed = time_module.perf_counter() - started
    print(
        f"\nplan smoke: {entries} entries -> {plan.summary.actions} actions, "
        f"{plan.summary.planned_bytes / 1024**2:,.0f} MiB planned in {elapsed:.2f}s"
    )
    assert entries >= 120_000
    assert elapsed < 120, f"plan generation took {elapsed:.1f}s"
    planner.validate_plan(plan.to_dict())
