def mini_plan(
    tmp_path: Path, files: tuple[gen_candidates.File, ...], *, rules_dir: Path | None = None
) -> planner.Plan:
    """Plan a small export with the fixture's defaults."""
    db_path = mini_index(tmp_path, files, rules_dir=rules_dir)
    conn = db.open_db(db_path)
    try:
        ruleset = (
            rules.load_rules(user_dir=rules_dir) if rules_dir is not None else rules.load_rules()
        )
        return planner.build_plan(
            conn,
            ruleset,
            targets=(D_TARGET,),
            min_size=MIN,
            top=0,
            now=NOW,
            db_path=str(db_path),
        )
    finally:
        conn.close()


