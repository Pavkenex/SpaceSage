def test_plan_id_changes_with_the_source_identity() -> None:
    """The id covers the source metadata: another export is another plan."""
    item = fake_candidate(r"C:\Temp\x.tmp")
    report = synthetic_report((item,))
    first = compose(report, source={"csv": "a.csv", "machine": "PC-1", "exported": "x"})
    second = compose(report, source={"csv": "a.csv", "machine": "PC-2", "exported": "x"})
    assert first.plan_id != second.plan_id


def test_plan_id_changes_with_the_action_list() -> None:
    """And it covers the actions: one different byte is a different plan."""
    item = fake_candidate(r"C:\Temp\x.tmp")
    report = synthetic_report((item,))
    plan = compose(report)
    tampered = planner.compose_plan(
        None,
        synthetic_report((fake_candidate(r"C:\Temp\x.tmp", size=MIN + 1),)),
        rules.load_rules(),
        targets=(D_TARGET,),
        source=dict(plan.source),
    )
    assert tampered.plan_id != plan.plan_id


