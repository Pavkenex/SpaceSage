def test_score_is_bytes_times_the_four_factors() -> None:
    """bytes x tier weight x confidence x recency, exactly."""
    # 200 days sits on the linear ramp between FRESH_DAYS and COLD_DAYS.
    factor = 0.5 + 0.5 * (200 - FRESH_DAYS) / (COLD_DAYS - FRESH_DAYS)
    score = candidates.score_candidate(1_000_000, "T1", 0.5, 200)
    assert score.tier_weight == 1.0
    assert score.recency_factor == pytest.approx(factor)
    assert score.value == pytest.approx(1_000_000 * 1.0 * 0.5 * factor)
    assert score.bytes == 1_000_000
    assert score.age_days == 200


def test_score_candidate_explains_itself() -> None:
    """Every factor is kept on the candidate, so the ranking can be re-derived."""
    score = candidates.score_candidate(2 * MIB, "T2", 0.7, 800)
    explanation = score.explain()
    assert "2.0 MiB" in explanation
    assert "0.60 tier" in explanation and "0.70 conf" in explanation
    assert "1.00 recency" in explanation and "age 800d" in explanation


def test_recency_factor_is_fresh_below_fresh_days() -> None:
    assert candidates.recency_factor(0) == pytest.approx(0.5)
    assert candidates.recency_factor(FRESH_DAYS) == pytest.approx(0.5)


def test_recency_factor_is_cold_at_cold_days_and_beyond() -> None:
    assert candidates.recency_factor(COLD_DAYS) == pytest.approx(1.0)
    assert candidates.recency_factor(COLD_DAYS * 5) == pytest.approx(1.0)


def test_recency_factor_rises_monotonically_with_age() -> None:
    fresh = candidates.recency_factor(40)
    middle = candidates.recency_factor(200)
    cold = candidates.recency_factor(400)
    assert 0.5 < fresh < middle < cold <= 1.0


def test_recency_factor_of_unknown_age_is_neutral() -> None:
    """A missing timestamp is neither fresh nor provably cold."""
    assert candidates.recency_factor(None) == pytest.approx(0.75)


def test_tier_weight_orders_disposable_data_first() -> None:
    scores = {
        tier: candidates.score_candidate(1000, tier, 1.0, COLD_DAYS).value
        for tier in ("T1", "T2", "T3")
    }
    assert scores == {"T1": 1000.0, "T2": 600.0, "T3": 200.0}


def test_tier_weights_mirror_the_module_definition() -> None:
    assert candidates.TIER_WEIGHTS == {"T1": 1.0, "T2": 0.6, "T3": 0.2}


def test_score_candidate_rejects_bad_input() -> None:
    with pytest.raises(CandidatesError):
        candidates.score_candidate(10, "T9", 0.5, None)
    with pytest.raises(CandidatesError):
        candidates.score_candidate(10, "T1", 1.5, None)
    with pytest.raises(CandidatesError):
        candidates.score_candidate(-1, "T1", 0.5, None)


