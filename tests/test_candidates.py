def test_considered_adds_up_with_suppression(tmp_path: Path) -> None:
    """listed = total - suppressed for every kind when nothing hits the buffer."""
    report = report_for(ingest_fixture(tmp_path))
    assert report.considered == sum(item.found for item in report.kinds)
    for block_summary in report.kinds:
        assert len(block_summary.candidates) == block_summary.total - block_summary.suppressed
        assert block_summary.beyond_buffer == 0  # 50 x OVERKEEP covers the fixture
    assert report.suppressed_nested + report.suppressed_duplicate == sum(
        item.suppressed for item in report.kinds
    )


def test_report_is_deterministic(tmp_path: Path) -> None:
    """Two runs over the same index agree on everything but the timestamp."""
    db_path = ingest_fixture(tmp_path)
    first = report_for(db_path).to_dict()
    second = report_for(db_path).to_dict()
    first.pop("generated")
    second.pop("generated")
    assert first == second


def test_report_never_writes_to_the_index(tmp_path: Path) -> None:
    """Candidates are derived: the index and its derived tables stay untouched."""
    db_path = ingest_fixture(tmp_path)
    conn = db.open_db(db_path)
    try:
        before = db.index_summary(conn)
        candidates.candidate_report(
            conn, rules.load_rules(), min_size=MIN, top=50, now=NOW, db_path=str(db_path)
        )
        after = db.index_summary(conn)
        categories = conn.execute("SELECT COUNT(*) FROM categories").fetchone()
    finally:
        conn.close()
    assert after == before
    assert categories[0] == 0


