@pytest.mark.slow
def test_perf_smoke_candidates(tmp_path: Path) -> None:
    """A large index produces the ranked lists in one streaming pass; prints the rate."""
    import time as time_module

    generated = gen.generate(
        tmp_path / "perf.csv",
        gen.GenOptions(
            seed=77,
            min_files=120_000,
            files_per_dir=12,
            dirs_per_dir=4,
            min_depth=6,
            collect_entries=False,
        ),
    )
    db_path = tmp_path / "perf.db"
    ingest_csv(generated.path, db_path)
    conn = db.open_db(db_path)
    ruleset = rules.load_rules()
    started = time_module.perf_counter()
    report = candidates.candidate_report(conn, ruleset, now=NOW, top=20, db_path=str(db_path))
    elapsed = time_module.perf_counter() - started
    entries = db.entry_count(conn)
    print(
        f"\ncandidates smoke: {entries} entries -> {report.considered} candidates found "
        f"in {elapsed:.2f}s ({entries / elapsed:,.0f} entries/s), "
        f"{len(report.candidates)} listed"
    )
    assert entries >= 120_000
    assert elapsed < 60, f"candidate generation took {elapsed:.1f}s"
    for block_summary in report.kinds:
        assert len(block_summary.candidates) <= 20
    conn.close()
