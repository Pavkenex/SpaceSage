def test_top_limits_rows_and_keeps_the_ranking(tmp_path: Path) -> None:
    db_path = ingest_fixture(tmp_path)
    limited = report_for(db_path, top=2)
    full = report_for(db_path)
    for kind in candidates.KINDS:
        assert len(block(limited, kind).candidates) == min(2, len(block(full, kind).candidates))
        assert listed(limited, kind) == listed(full, kind)[:2]
        assert block(limited, kind).found == block(full, kind).found


def test_top_zero_lists_every_candidate(tmp_path: Path) -> None:
    """top=0 removes the selection buffer: nothing is dropped for ranking."""
    db_path = ingest_fixture(tmp_path)
    unlimited = report_for(db_path, top=0)
    bounded = report_for(db_path)
    for kind in candidates.KINDS:
        assert block(unlimited, kind).beyond_buffer == 0
        assert len(block(unlimited, kind).candidates) == (
            block(unlimited, kind).total - block(unlimited, kind).suppressed
        )
        assert listed(unlimited, kind)[: len(block(bounded, kind).candidates)] == listed(
            bounded, kind
        )


