def ingest_fixture(tmp_path: Path, name: str = "candidates.csv") -> Path:
    """Ingest a committed fixture and return the index path."""
    db_path = tmp_path / "index.db"
    ingest_csv(DATA_DIR / name, db_path)
    return db_path


def report_for(db_path: Path, **kwargs: object) -> candidates.CandidateReport:
    """Run the full report on an index with the test defaults."""
    options: dict[str, object] = {"min_size": MIN, "top": 50, "now": NOW, "db_path": str(db_path)}
    options.update(kwargs)
    conn = db.open_db(db_path)
    try:
        return candidates.candidate_report(conn, rules.load_rules(), **options)  # type: ignore[arg-type]
    finally:
        conn.close()


def block(report: candidates.CandidateReport, kind: str) -> KindSummary:
    """The block of one kind (fails loudly when the kind is missing)."""
    found = report.kind(kind)
    assert found is not None, f"kind {kind!r} missing from the report"
    return found


def listed(report: candidates.CandidateReport, kind: str) -> list[str]:
    """Listed paths of one kind, best first."""
    return [item.path for item in block(report, kind).candidates]


def by_path(report: candidates.CandidateReport, kind: str) -> dict[str, Candidate]:
    """Listed candidates of one kind, keyed by path."""
    return {item.path: item for item in block(report, kind).candidates}


def mini_export(tmp_path: Path, files: tuple[gen_candidates.File, ...]) -> Path:
    """Write a throwaway WizTree CSV (uses the fixture generator's emitter)."""
    rows = gen_candidates.build_rows(files, {})
    target = tmp_path / "export.csv"
    gen_candidates.write_export(target, rows)
    return target


def run_cli(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "spacesage", *args],
        capture_output=True,
        text=True,
        check=False,
    )


